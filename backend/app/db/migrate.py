"""Programmatic Alembic entry points (T-003).

The CLI (`cd backend && alembic upgrade head`) and these helpers share one
`alembic.ini` + `alembic/env.py`, so the schema reaches the same revision
whichever path an operator takes:

    from app.db.migrate import upgrade_to_head, current_revision
    upgrade_to_head()                 # uses POSTGRESQL_URI
    upgrade_to_head(connection=conn)  # migrate an already-open connection

`connection=` is what the test-suite uses for in-memory SQLite, where every
new connection is a brand-new empty database.
"""

from __future__ import annotations

import os
from pathlib import Path

from alembic import command
from alembic.config import Config
from alembic.runtime.migration import MigrationContext
from alembic.script import ScriptDirectory
from sqlalchemy.engine import Connection

BACKEND_ROOT = Path(__file__).resolve().parents[2]
ALEMBIC_INI = BACKEND_ROOT / "alembic.ini"
SCRIPT_LOCATION = BACKEND_ROOT / "alembic"


def alembic_config(
    *,
    url: str | None = None,
    connection: Connection | None = None,
    quiet: bool = True,
) -> Config:
    """Build an Alembic Config pointed at backend/alembic.

    `url` wins over `POSTGRESQL_URI`; `connection` wins over both. The URL is
    passed through `config.attributes` rather than `set_main_option` so a
    password containing `%` never trips ConfigParser interpolation.
    """
    cfg = Config(str(ALEMBIC_INI))
    cfg.set_main_option("script_location", str(SCRIPT_LOCATION))
    if url:
        cfg.attributes["sqlalchemy_url"] = url
    if connection is not None:
        cfg.attributes["connection"] = connection
    if quiet:
        cfg.attributes["skip_logging"] = True
    return cfg


def head_revision() -> str | None:
    """Return the newest revision id present in alembic/versions."""
    script = ScriptDirectory.from_config(alembic_config())
    return script.get_current_head()


def current_revision(connection: Connection) -> str | None:
    """Return the revision stamped in `alembic_version` (None = never migrated)."""
    return MigrationContext.configure(connection).get_current_revision()


def upgrade_to_head(
    *, url: str | None = None, connection: Connection | None = None
) -> None:
    """Apply every pending migration. Idempotent at head."""
    if url is None and connection is None and not os.environ.get("POSTGRESQL_URI"):
        from app.config import get_settings

        url = get_settings().postgresql_uri or None
        if url is None:
            raise RuntimeError("POSTGRESQL_URI is missing — set it in backend/.env")
    command.upgrade(alembic_config(url=url, connection=connection), "head")


def downgrade_to_base(
    *, url: str | None = None, connection: Connection | None = None
) -> None:
    """Roll every migration back (drops all tables). Test + ops use only."""
    command.downgrade(alembic_config(url=url, connection=connection), "base")


def check_in_sync(*, url: str | None = None, connection: Connection | None = None) -> None:
    """Raise `alembic.util.exc.AutogenerateDiffsDetected` if models drifted.

    Equivalent to `alembic check`; meant for CI against a real Postgres.
    """
    command.check(alembic_config(url=url, connection=connection))


__all__ = [
    "ALEMBIC_INI",
    "SCRIPT_LOCATION",
    "alembic_config",
    "check_in_sync",
    "current_revision",
    "downgrade_to_base",
    "head_revision",
    "upgrade_to_head",
]
