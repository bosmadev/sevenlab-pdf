"""Alembic migration checks (T-003).

Offline (always run) — on an in-memory SQLite engine:
    - `upgrade head` creates every table + index that `Base.metadata` declares,
      with identical column names and nullability.
    - `downgrade base` removes everything again, leaving only alembic_version.
    - the repo has exactly one head, so `alembic upgrade head` is unambiguous.

Online (skipped without `POSTGRESQL_URI`) — against a real PostgreSQL:
    - `alembic check` reports zero diffs between models and migrations.
    - upgrade → downgrade → upgrade round-trips cleanly.
"""

from __future__ import annotations

import os

import pytest
from sqlalchemy import create_engine, inspect

from app.db import models  # noqa: F401 — register ORM tables on Base
from app.db.migrate import (
    current_revision,
    downgrade_to_base,
    head_revision,
    upgrade_to_head,
)
from app.db.postgres import Base

EXPECTED_TABLES = {"users", "documents", "sessions", "audit_log"}


@pytest.fixture
def sqlite_conn():
    engine = create_engine("sqlite:///:memory:", future=True)
    with engine.connect() as conn:
        yield conn
    engine.dispose()


def test_single_head() -> None:
    from alembic.script import ScriptDirectory

    from app.db.migrate import alembic_config

    heads = ScriptDirectory.from_config(alembic_config()).get_heads()
    assert heads == ["0001"], heads
    assert head_revision() == "0001"


def test_upgrade_head_matches_metadata_on_sqlite(sqlite_conn) -> None:
    assert current_revision(sqlite_conn) is None
    upgrade_to_head(connection=sqlite_conn)
    assert current_revision(sqlite_conn) == head_revision()

    insp = inspect(sqlite_conn)
    tables = set(insp.get_table_names()) - {"alembic_version"}
    assert tables == EXPECTED_TABLES == set(Base.metadata.tables), tables

    for name, table in Base.metadata.tables.items():
        migrated_cols = {c["name"]: c for c in insp.get_columns(name)}
        model_cols = {c.name: c for c in table.columns}
        assert set(migrated_cols) == set(model_cols), (name, set(migrated_cols) ^ set(model_cols))
        for col_name, model_col in model_cols.items():
            assert migrated_cols[col_name]["nullable"] == model_col.nullable, (
                name,
                col_name,
            )

        migrated_idx = {i["name"]: i for i in insp.get_indexes(name)}
        model_idx = {i.name: i for i in table.indexes}
        assert set(migrated_idx) == set(model_idx), (name, set(migrated_idx) ^ set(model_idx))
        for idx_name, model_index in model_idx.items():
            assert migrated_idx[idx_name]["column_names"] == [
                c.name for c in model_index.columns
            ], (name, idx_name)
            assert bool(migrated_idx[idx_name]["unique"]) == bool(model_index.unique), (
                name,
                idx_name,
            )

        migrated_fks = {
            (tuple(fk["constrained_columns"]), fk["referred_table"])
            for fk in insp.get_foreign_keys(name)
        }
        model_fks = {
            (tuple(c.name for c in fk.columns), fk.referred_table.name)
            for fk in table.foreign_key_constraints
        }
        assert migrated_fks == model_fks, (name, migrated_fks ^ model_fks)


def test_downgrade_base_drops_everything_on_sqlite(sqlite_conn) -> None:
    upgrade_to_head(connection=sqlite_conn)
    downgrade_to_base(connection=sqlite_conn)
    assert current_revision(sqlite_conn) is None
    remaining = set(inspect(sqlite_conn).get_table_names()) - {"alembic_version"}
    assert remaining == set(), remaining


def test_upgrade_is_idempotent_at_head(sqlite_conn) -> None:
    upgrade_to_head(connection=sqlite_conn)
    upgrade_to_head(connection=sqlite_conn)
    assert current_revision(sqlite_conn) == head_revision()


@pytest.mark.skipif(
    not os.environ.get("POSTGRESQL_URI"),
    reason="live PostgreSQL required (export POSTGRESQL_URI)",
)
def test_live_postgres_round_trip_and_check() -> None:
    """upgrade → check (zero diffs) → downgrade → upgrade on a real Postgres."""
    from alembic.util.exc import AutogenerateDiffsDetected

    from app.db.migrate import check_in_sync

    url = os.environ["POSTGRESQL_URI"]
    engine = create_engine(url, future=True)
    try:
        with engine.connect() as conn:
            upgrade_to_head(connection=conn)
            assert current_revision(conn) == head_revision()
            tables = set(inspect(conn).get_table_names()) - {"alembic_version"}
            assert tables == EXPECTED_TABLES, tables

        try:
            check_in_sync(url=url)
        except AutogenerateDiffsDetected as exc:  # pragma: no cover — report the drift
            pytest.fail(f"models drifted from migrations: {exc}")

        with engine.connect() as conn:
            downgrade_to_base(connection=conn)
            assert current_revision(conn) is None
        with engine.connect() as conn:
            upgrade_to_head(connection=conn)
            assert current_revision(conn) == head_revision()
    finally:
        engine.dispose()
